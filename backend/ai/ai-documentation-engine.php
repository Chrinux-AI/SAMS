        return $pdfContent;
    }

    /**
     * Create DOCX content
     */
    private function createDOCXContent($title, $content, $metadata)
    {
        // For now, create a simple HTML-based DOCX
        // In production, use a proper DOCX library like PHPWord

        $html = $this->generateDocumentHTML($title, $content, $metadata);

        // Create DOCX content (simplified approach)
        $docxContent = "<!DOCTYPE html>
<html>
<head>
    <title>{$title}</title>
    <style>
        body { font-family: Arial, sans-serif; margin: 40px; }
        .header { text-align: center; margin-bottom: 30px; }
        .content { line-height: 1.6; }
        .footer { margin-top: 50px; text-align: center; font-size: 12px; color: #666; }
    </style>
</head>
<body>
    <div class='header'>
        <h1>{$title}</h1>
        <p>Generated on " . date('Y-m-d H:i:s') . "</p>
    </div>
    <div class='content'>
        {$html}
    </div>
    <div class='footer'>
        <p>Generated by " . APP_NAME . " AI Documentation Engine</p>
    </div>
