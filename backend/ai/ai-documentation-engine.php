<?php
require_once __DIR__ . '/../includes/config.php';
require_once __DIR__ . '/../includes/functions.php';
require_once __DIR__ . '/../includes/database.php';

class AIDocumentationEngine
{
    private $tenantId;
    private $userId;

    public function __construct($userId = null, $tenantId = null)
    {
        $this->userId = $userId ?? ($_SESSION['user_id'] ?? 0);
        $this->tenantId = $tenantId ?? ($_SESSION['tenant_id'] ?? 1);
    }

    /**
     * Generate PDF document from dashboard content
     */
    public function generatePDF($title, $content, $metadata = [])
    {
        try {
            $documentId = $this->createDocumentRecord($title, 'pdf', $content, $metadata);

            // Generate PDF using TCPDF or similar library
            $pdfContent = $this->createPDFContent($title, $content, $metadata);

            // Save PDF file
            $filePath = $this->saveDocumentFile($documentId, $pdfContent, 'pdf');

            // Update document record with file path
            $this->updateDocumentFile($documentId, $filePath);

            return [
                'success' => true,
                'document_id' => $documentId,
                'file_path' => $filePath,
                'download_url' => "/attendance/docs/download.php?id=" . $documentId
            ];
        } catch (Exception $e) {
            error_log("AIDocumentationEngine::generatePDF error: " . $e->getMessage());
            return [
                'success' => false,
                'error' => $e->getMessage()
            ];
        }
    }

    /**
     * Generate DOCX document from dashboard content
     */
    public function generateDOCX($title, $content, $metadata = [])
    {
        try {
            $documentId = $this->createDocumentRecord($title, 'docx', $content, $metadata);

            // Generate DOCX content
            $docxContent = $this->createDOCXContent($title, $content, $metadata);

            // Save DOCX file
            $filePath = $this->saveDocumentFile($documentId, $docxContent, 'docx');

            // Update document record with file path
            $this->updateDocumentFile($documentId, $filePath);

            return [
                'success' => true,
                'document_id' => $documentId,
                'file_path' => $filePath,
                'download_url' => "/attendance/docs/download.php?id=" . $documentId
            ];
        } catch (Exception $e) {
            error_log("AIDocumentationEngine::generateDOCX error: " . $e->getMessage());
            return [
                'success' => false,
                'error' => $e->getMessage()
            ];
        }
    }

    /**
     * Create document record in database
     */
    private function createDocumentRecord($title, $type, $content, $metadata)
    {
        try {
            $documentId = db()->insert('ai_documents', [
                'tenant_id' => $this->tenantId,
                'user_id' => $this->userId,
                'title' => $title,
                'type' => $type,
                'content' => json_encode($content),
                'metadata' => json_encode($metadata),
                'status' => 'processing',
                'created_at' => date('Y-m-d H:i:s'),
                'updated_at' => date('Y-m-d H:i:s')
            ]);

            return $documentId;
        } catch (Exception $e) {
            error_log("AIDocumentationEngine::createDocumentRecord error: " . $e->getMessage());
            throw $e;
        }
    }

    /**
     * Create PDF content
     */
    private function createPDFContent($title, $content, $metadata)
    {
        // For now, create a simple HTML-based PDF
        // In production, use a proper PDF library like TCPDF or DomPDF

        $html = $this->generateDocumentHTML($title, $content, $metadata);

        // Convert HTML to PDF (simplified approach)
        // In production, this would use a proper PDF generation library
        $pdfContent = "<!DOCTYPE html>
<html>
<head>
    <title>{$title}</title>
    <style>
        body { font-family: Arial, sans-serif; margin: 40px; }
        .header { text-align: center; margin-bottom: 30px; }
        .content { line-height: 1.6; }
        .footer { margin-top: 50px; text-align: center; font-size: 12px; color: #666; }
    </style>
</head>
<body>
    <div class='header'>
        <h1>{$title}</h1>
        <p>Generated on " . date('Y-m-d H:i:s') . "</p>
    </div>
    <div class='content'>
        {$html}
    </div>
    <div class='footer'>
        <p>Generated by " . APP_NAME . " AI Documentation Engine</p>
    </div>
